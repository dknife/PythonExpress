# 코드 12.5: 열 선택, 행 선택, 조건 필터링

import pandas as pd

# 코드 12.2의 df 준비
df = pd.DataFrame({
    '이름': ['홍길동', '김철수',
        '이영희', '박지민'],
    '국어': [85, 92, 78, 95],
    '영어': [90, 88, 82, 91],
    '수학': [78, 95, 88, 87]
})

# 열 선택
print(df['이름'])            # 열 하나 -> Series
print(df[['이름', '국어']])  # 열 여러 개 -> DataFrame

# 행 선택
print(df.loc[0])     # 레이블 인덱스 0의 행
print(df.iloc[0:2])  # 위치 기반 행 선택 (0~1)

# 조건 필터링
print(df[df['국어'] >= 90]) # 국어 점수 90 이상인 학생
